


// There is two types of data types in Java. one is primitive data types and another is non-primitive data types. 

// parmitive data types examples are int, float, double, char, boolean, byte, short, long.
// non-primitive data types examples are String, Array, Class, Interface, etc.
// example of primitive data types in Java

class PrimitiveDataTypes{
    public static void main(String[] args){


        int a = 10; // integer data type
        float b = 10.5f; // float data type
        double c = 20.55544566457; // double data type
        char d = 'A'; // character data type
        String str = "Hello, World!"; // String data type
        boolean e = true; // boolean data type
        byte f = 10; // byte data type
        short g = 100; // short data type
        long h = 100545535353536230L; // long data type

        System.out.println("Integer: " + a);
        System.out.println("Float: " + b);
        System.out.println("Double: " + c);
        System.out.println("Character: " + d);
        System.out.println("String: " + str);
        System.out.println("Boolean: " + e);
        System.out.println("Byte: " + f);
        System.out.println("Short: " + g);
        System.out.println("Long: " + h);

    }
}

// way to run the program in terminal
// javac PrimitiveDataTypes.java (compile the program, filename)
// java PrimitiveDataTypes(class name)